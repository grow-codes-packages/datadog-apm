"""Live checks of the Python package against a real Datadog Agent and Datadog APM (GRO-1385).

Service-owned (not generated by sdk-kit). It covers what the Docker suite cannot: the whole
``DatadogSpansQuery`` (SaaS-only, see ``docs/compatibility.md``). It sends a two-span trace through
``init_tracing`` (OTLP) to a real Datadog Agent that forwards it to Datadog, then reads it back
through the Spans API (``wait_for_trace``, ``get_trace``, ``search_spans``, ``search_traces``,
``aggregate_spans``) and checks ``list_services``, ``list_operations`` and the key validation.

Both spans are marked as errors, so Datadog's default ``Error Default`` retention filter indexes
them; a retention filter that keeps 100 % of ``service:grow-sdk-live-python`` makes the run
independent of that default.

Environment (the same names as the GitHub organisation secrets):

    DATADOG_API_KEY   API key of the Datadog organisation used for live checks (required)
    DATADOG_APP_KEY   application key with apm_read (required)
    DATADOG_SITE      Datadog site, default datadoghq.eu
    LIVE_TIMEOUT_S    how long to wait for the trace to become searchable, default 300
    GROW_DATADOG_APM_URL / GROW_DATADOG_APM_OTLP_ENDPOINT
                      the Agent (default http://127.0.0.1:8126 and :4318); ``live/run.sh``
                      starts a ``datadog/agent`` container when neither the URL nor
                      DD_AGENT_HOST is set

Without the two keys it prints ``skipped: no credentials`` and exits 0. Run it with
``make -C live live``. ``--check-credentials`` only reports whether the keys are set (exit 0) or
not (exit 78) and never imports the SDK.
"""

from __future__ import annotations

import os
import sys
import time
import uuid
from collections.abc import Callable, Iterable, Mapping
from datetime import datetime, timedelta, timezone
from typing import Any

REQUIRED_ENV = ("DATADOG_API_KEY", "DATADOG_APP_KEY")
DEFAULT_SITE = "datadoghq.eu"
SERVICE = "grow-sdk-live-python"
LIVE_ENV = "live"
ROOT_SPAN = "grow.live.checkout"
CHILD_SPAN = "grow.live.load-cart"
EXIT_SKIPPED = 78  # EX_CONFIG: only used by --check-credentials
PASSTHROUGH = ("DD_AGENT_HOST", "DD_TRACE_AGENT_PORT", "DD_TRACE_AGENT_URL")


# --------------------------------------------------------------------------- harness


class CheckFailedError(AssertionError):
    """An expectation of a live check did not hold."""


def expect(condition: object, message: str) -> None:
    """Raise :class:`CheckFailedError` with ``message`` unless ``condition`` is truthy."""
    if not condition:
        raise CheckFailedError(message)


def poll(fn: Callable[[], Any], *, timeout_s: float, interval_s: float, what: str) -> Any:
    """Call ``fn`` until it returns a truthy value; builtin ``TimeoutError`` at the deadline."""
    deadline = time.monotonic() + timeout_s
    while True:
        value = fn()
        if value:
            return value
        if time.monotonic() + interval_s > deadline:
            raise TimeoutError(f"{what}: not seen within {timeout_s:.0f} s")
        time.sleep(interval_s)


def _annotation(text: str) -> str:
    return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


class Suite:
    """Runs named checks in order and records PASS, FAIL, WARN or SKIP for each."""

    def __init__(self, title: str) -> None:
        self.title = title
        self.results: list[tuple[str, str, str]] = []
        self.passed: set[str] = set()
        self.github = os.environ.get("GITHUB_ACTIONS") == "true"

    def check(
        self,
        name: str,
        fn: Callable[[], Any],
        *,
        needs: Iterable[str] = (),
        warn_only: bool = False,
    ) -> Any:
        """Run ``fn``; a check whose ``needs`` did not pass is skipped. Returns ``fn()``."""
        missing = [n for n in needs if n not in self.passed]
        if missing:
            self._record("SKIP", name, "needs " + ", ".join(missing))
            return None
        started = time.monotonic()
        try:
            value = fn()
        except Exception as err:  # noqa: BLE001 - every failure is reported, the suite goes on
            status = "WARN" if warn_only else "FAIL"
            self._record(status, name, f"{type(err).__name__}: {err}")
            return None
        self.passed.add(name)
        self._record("PASS", name, f"{time.monotonic() - started:.1f} s")
        return value

    def _record(self, status: str, name: str, detail: str) -> None:
        self.results.append((status, name, detail))
        print(f"{status:4} {name} ({detail})", flush=True)
        if self.github and status in ("FAIL", "WARN"):
            level = "error" if status == "FAIL" else "warning"
            print(f"::{level} title=live: {_annotation(name)}::{_annotation(detail)}", flush=True)

    def finish(self) -> int:
        """Print the summary (and the GitHub step summary); 1 when a check failed."""
        counts = {s: sum(1 for r in self.results if r[0] == s) for s in ("PASS", "FAIL", "WARN")}
        counts["SKIP"] = len(self.results) - sum(counts.values())
        line = ", ".join(f"{n} {s.lower()}" for s, n in counts.items())
        print(f"\n{self.title}: {line}", flush=True)
        summary = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary:
            rows = "\n".join(f"| {s} | {n} | {d.replace('|', '/')} |" for s, n, d in self.results)
            with open(summary, "a", encoding="utf-8") as fh:
                fh.write(f"### {self.title}\n\n{line}\n\n| Result | Check | Detail |\n")
                fh.write(f"| - | - | - |\n{rows}\n\n")
        return 1 if counts["FAIL"] else 0


def info(text: str) -> None:
    """An informational line under the current check."""
    print(f"     {text}", flush=True)


def missing_credentials(environ: Mapping[str, str]) -> list[str]:
    """Names of the required variables that are unset or empty."""
    return [name for name in REQUIRED_ENV if not environ.get(name, "").strip()]


# --------------------------------------------------------------------------- live checks


def run() -> int:
    """All live checks; returns the exit code."""
    import grow_datadog_apm as sdk

    site = os.environ.get("DATADOG_SITE", "").strip() or DEFAULT_SITE
    timeout_s = float(os.environ.get("LIVE_TIMEOUT_S", "") or 300)
    marker = f"growlive{uuid.uuid4().hex[:16]}"
    environ = {
        "DD_API_KEY": os.environ["DATADOG_API_KEY"].strip(),
        "DD_APP_KEY": os.environ["DATADOG_APP_KEY"].strip(),
        "DD_SITE": site,
        **{k: v for k, v in os.environ.items() if k in PASSTHROUGH and v},
        **{k: v for k, v in os.environ.items() if k.startswith("GROW_DATADOG_APM_")},
    }
    suite = Suite(f"datadog-apm live checks (Python {sdk.__version__}, site {site})")
    print(f"marker {marker}, service {SERVICE}, env {LIVE_ENV}\n", flush=True)
    state: dict[str, Any] = {}

    def build() -> None:
        config = sdk.DatadogApmConfig.from_env(environ, service_name=SERVICE, environment=LIVE_ENV)
        info(f"agent {config.url}, otlp {config.otlp_traces_endpoint}, api {config.api_url}")
        state["client"] = sdk.DatadogApmClient(config)

    suite.check("config + client", build)
    client: Any = state.get("client")
    if client is None:
        return suite.finish()

    with client:
        spans: Any = client.spans

        def agent_health() -> None:
            status = poll(
                lambda: (s := client.health()).healthy and s,
                timeout_s=90,
                interval_s=3,
                what="healthy Agent",
            )
            info(f"{status.status} {dict(status.details)}")
            info(f"Agent {client.server_version()}, ping {client.ping():.0f} ms")

        suite.check("Agent health + server_version + ping", agent_health)

        def keys() -> None:
            info(f"validate_keys {spans.ping():.0f} ms")

        def wrong_keys() -> None:
            bad = sdk.DatadogApmConfig.from_env({**environ, "DD_APP_KEY": "0" * 40})
            with sdk.DatadogSpansQuery(bad) as other:
                try:
                    other.ping()
                except sdk.AuthenticationError as err:
                    info(f"HTTP {err.http_status}")
                    return
            raise CheckFailedError("a wrong application key was accepted")

        suite.check("spans.ping (validate_keys, real keys)", keys)
        suite.check("spans.ping (wrong app key -> AUTHENTICATION)", wrong_keys)

        def send_trace() -> None:
            handle = client.init_tracing(service_name=SERVICE, environment=LIVE_ENV)
            info(f"exporting to {handle.endpoint}")
            attrs = {"grow.live.marker": marker}
            with sdk.with_span(ROOT_SPAN, kind="server", attributes=attrs) as root:
                state["root_span_id"] = format(root.get_span_context().span_id, "016x")
                with sdk.with_span(CHILD_SPAN, attributes=attrs):
                    # Error spans are indexed by Datadog's default "Error Default" filter.
                    sdk.set_error(RuntimeError(f"{marker} child failure (expected)"))
                state["trace_id"] = sdk.current_trace_id()
                sdk.set_error(ValueError(f"{marker} root failure (expected)"))
            handle.force_flush(30)
            state["sent_at"] = time.monotonic()
            state["start"] = datetime.now(timezone.utc) - timedelta(minutes=30)
            info(f"trace {state['trace_id']}")

        suite.check("init_tracing + send a 2-span trace to the Agent", send_trace)
        sent = ["init_tracing + send a 2-span trace to the Agent"]

        def wait_for_trace() -> None:
            trace = spans.wait_for_trace(
                state["trace_id"], timeout_s=timeout_s, interval_s=5, min_spans=2
            )
            delay = time.monotonic() - state["sent_at"]
            info(f"searchable after {delay:.0f} s with {len(trace.spans)} spans")

        suite.check("wait_for_trace (2 spans)", wait_for_trace, needs=sent)
        found = [*sent, "wait_for_trace (2 spans)"]

        def preview_diagnosis() -> None:
            trace = spans.get_trace(state["trace_id"], preview=True)
            n = len(trace.spans) if trace else 0
            raise CheckFailedError(
                f"trace-by-id finds {n} spans but the Spans API none: the spans were ingested "
                f"but not indexed; add a retention filter for service:{SERVICE}"
                if n
                else "the trace never reached Datadog (check the Agent and DATADOG_SITE)"
            )

        if "wait_for_trace (2 spans)" not in suite.passed and sent[0] in suite.passed:
            suite.check("diagnosis: get_trace(preview=True)", preview_diagnosis, warn_only=True)

        def get_trace() -> None:
            trace = spans.get_trace(state["trace_id"], from_=state["start"])
            expect(trace is not None, "get_trace() found nothing")
            by_name = {s.name: s for s in trace.spans}
            info(", ".join(f"{s.name} ({s.service_name}, {s.status.code})" for s in trace.spans))
            expect(set(by_name) == {ROOT_SPAN, CHILD_SPAN}, f"span names {sorted(by_name)}")
            root, child = by_name[ROOT_SPAN], by_name[CHILD_SPAN]
            expect(root.span_id == state["root_span_id"], "root span id differs")
            expect(child.parent_span_id == root.span_id, "child is not linked to the root")
            expect(root.service_name == SERVICE, f"service {root.service_name!r}")
            expect(root.status.code == "error", f"root status {root.status}")
            info(f"root error.type = {root.attributes.get('error.type')!r}")
            state["trace"] = trace

        suite.check("get_trace (spans search: ids, parent, service, error)", get_trace, needs=found)

        def full_trace_id() -> None:
            ids = {sp.trace_id for sp in state["trace"].spans}
            expect(ids == {state["trace_id"]}, f"span trace ids {sorted(ids)}")

        suite.check(
            "span trace ids carry the full 128-bit id",
            full_trace_id,
            needs=["get_trace (spans search: ids, parent, service, error)"],
            warn_only=True,
        )

        def get_trace_preview() -> None:
            trace = spans.get_trace(state["trace_id"], preview=True)
            expect(trace is not None and len(trace.spans) == 2, f"preview trace: {trace}")

        suite.check(
            "get_trace(preview=True) (trace-by-id, x-unstable)",
            get_trace_preview,
            needs=found,
            warn_only=True,
        )

        query = f"service:{SERVICE} @grow.live.marker:{marker}"

        def search_spans() -> None:
            items = list(spans.search_spans(query=query, from_=state["start"], limit=1))
            expect(len(items) == 2, f"{len(items)} spans (paged 1 per request)")
            expect({i.span.name for i in items} == {ROOT_SPAN, CHILD_SPAN}, "span names differ")

        suite.check("search_spans (by marker, cursor paging)", search_spans, needs=found)

        def search_traces() -> None:
            q = sdk.TraceSearchQuery(
                service=SERVICE, tags={"grow.live.marker": marker}, start=state["start"]
            )
            ids = [t.trace_id for t in spans.search_traces(q)]
            expect(ids == [state["trace_id"]], f"trace ids {ids}")

        suite.check("search_traces (service + tag)", search_traces, needs=found)

        def aggregate() -> None:
            result = spans.aggregate_spans(
                [sdk.SpanCompute("count")],
                [sdk.SpanGroupBy("resource_name")],
                query=query,
                from_=state["start"],
            )
            counts = {str(b.by.get("resource_name")): b.computes.get("c0") for b in result.buckets}
            info(f"{counts}")
            expect(sum(float(v or 0) for v in counts.values()) == 2, f"counts {counts}")

        suite.check("aggregate_spans (count by resource_name)", aggregate, needs=found)

        def list_operations() -> None:
            ops = spans.list_operations(SERVICE)
            info(f"{ops}")
            expect({ROOT_SPAN, CHILD_SPAN} <= set(ops), f"operations {ops}")

        suite.check("list_operations", list_operations, needs=found)

        def list_services() -> None:
            services = poll(
                lambda: (s := spans.list_services(env=LIVE_ENV)) and SERVICE in s and s,
                timeout_s=180,
                interval_s=15,
                what=f"{SERVICE} in list_services(env={LIVE_ENV!r})",
            )
            info(f"{len(services)} services in env {LIVE_ENV}")

        suite.check("list_services (includes the service)", list_services, needs=sent)

        def dependencies() -> None:
            try:
                spans.get_dependencies()
            except sdk.UnsupportedError:
                return
            raise CheckFailedError("get_dependencies() did not raise UnsupportedError")

        suite.check("get_dependencies -> UNSUPPORTED", dependencies)

    return suite.finish()


def main(argv: list[str]) -> int:
    missing = missing_credentials(os.environ)
    if missing:
        print(f"skipped: no credentials ({', '.join(missing)} not set); live checks not run")
        return EXIT_SKIPPED if "--check-credentials" in argv else 0
    if "--check-credentials" in argv:
        print("credentials: set")
        return 0
    return run()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
